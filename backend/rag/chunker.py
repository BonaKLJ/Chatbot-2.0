"""
Recursive character text chunker for RAG applications.

This module implements a pure Python text splitter that recursively divides text
using a hierarchy of separators (paragraph breaks, single newlines, sentence breaks,
spaces, and character fallback) to preserve semantic coherence within chunks.
"""

from typing import List


def _split_text(text: str, separators: List[str], chunk_size: int) -> List[str]:
    """
    Recursively split text into pieces where each piece is <= chunk_size characters.

    Args:
        text: Text string to split.
        separators: Priority list of separator strings to try.
        chunk_size: Maximum allowed length for any individual piece.

    Returns:
        List of text pieces (with separators preserved) where each piece <= chunk_size.
    """
    if not text:
        return []
    if len(text) <= chunk_size:
        return [text]

    # Find the first separator present in text
    selected_sep = None
    for sep in separators:
        if sep == "":
            selected_sep = ""
            break
        if sep in text:
            selected_sep = sep
            break

    # If no separator found or empty string reached, fall back to character split
    if selected_sep == "" or selected_sep is None:
        return list(text)

    # Split text by selected separator and re-attach separator to split pieces
    splits = text.split(selected_sep)
    next_separators = separators[separators.index(selected_sep) + 1 :]

    pieces: List[str] = []
    for i, split_part in enumerate(splits):
        # Re-attach separator to all splits except the last one
        piece = split_part + (selected_sep if i < len(splits) - 1 else "")
        if not piece:
            continue

        if len(piece) <= chunk_size:
            pieces.append(piece)
        else:
            # Piece exceeds chunk_size; recursively split using lower-priority separators
            sub_pieces = _split_text(piece, next_separators, chunk_size)
            pieces.extend(sub_pieces)

    return pieces


def _merge_pieces(pieces: List[str], chunk_size: int, chunk_overlap: int) -> List[str]:
    """
    Merge small text pieces into chunks of max length chunk_size, maintaining chunk_overlap.

    Args:
        pieces: Small text pieces generated by _split_text.
        chunk_size: Maximum character length for each merged chunk.
        chunk_overlap: Desired character overlap between consecutive chunks.

    Returns:
        List of merged chunk strings.
    """
    if not pieces:
        return []

    chunks: List[str] = []
    current_pieces: List[str] = []
    current_len = 0

    for piece in pieces:
        piece_len = len(piece)

        # If adding piece exceeds chunk_size, emit current chunk and build overlap window
        if current_len + piece_len > chunk_size and current_pieces:
            chunk_str = "".join(current_pieces).strip()
            if chunk_str:
                chunks.append(chunk_str)

            # Gather pieces from the end of current_pieces to satisfy chunk_overlap
            overlap_pieces: List[str] = []
            overlap_len = 0

            for p in reversed(current_pieces):
                if overlap_len + len(p) <= chunk_overlap:
                    overlap_pieces.insert(0, p)
                    overlap_len += len(p)
                else:
                    break

            # If overlap + new piece exceeds chunk_size, drop pieces from front until it fits
            while overlap_pieces and (overlap_len + piece_len > chunk_size):
                dropped = overlap_pieces.pop(0)
                overlap_len -= len(dropped)

            current_pieces = overlap_pieces
            current_len = overlap_len

        current_pieces.append(piece)
        current_len += piece_len

    # Emit the remaining chunk
    if current_pieces:
        chunk_str = "".join(current_pieces).strip()
        if chunk_str:
            chunks.append(chunk_str)

    return chunks


def chunk_text(text: str, chunk_size: int = 500, chunk_overlap: int = 50) -> list[str]:
    """
    Split input text recursively into semantically coherent chunks.

    Tries splitting on paragraph breaks ("\\n\\n") first, then single newlines ("\\n"),
    sentence breaks (". "), spaces (" "), and hard character splits ("") as fallback.

    Args:
        text: Input text string to chunk.
        chunk_size: Maximum character length for each chunk (default: 500).
        chunk_overlap: Repeated characters between consecutive chunks (default: 50).

    Returns:
        List of text chunks, each <= chunk_size characters.
    """
    if not text or not text.strip():
        return []

    if chunk_size <= 0:
        raise ValueError("chunk_size must be greater than 0")

    if chunk_overlap < 0:
        chunk_overlap = 0

    if chunk_overlap >= chunk_size:
        chunk_overlap = max(0, chunk_size - 1)

    separators = ["\n\n", "\n", ". ", " ", ""]

    # Step 1: Recursively split text into pieces each <= chunk_size
    pieces = _split_text(text, separators, chunk_size)

    # Step 2: Combine pieces into final overlapping chunks
    chunks = _merge_pieces(pieces, chunk_size, chunk_overlap)

    return chunks


